import { syncClassEffects } from '../helpers/class-effects.mjs';
import { validateTraditionChange } from '../helpers/miko.mjs';

/**
 * Extend the base Actor document by defining a custom roll data structure which is ideal for the Simple system.
 * @extends {Actor}
 */
export class CasusBelliActor extends Actor {
  /** @override */
  prepareData() {
    // Prepare data for the actor. Calling the super version of this executes
    // the following, in order: data reset (to clear active effects),
    // prepareBaseData(), prepareEmbeddedDocuments() (including active effects),
    // prepareDerivedData().
    super.prepareData();
  }

  /** @override */
  prepareBaseData() {
    // Foundry's Actor#prepareBaseData resets Active Effect overrides, statuses, and application
    // phases. It must run, or Active Effects fail on the second data preparation.
    super.prepareBaseData();
    // Data modifications in this step occur before processing embedded
    // documents or derived data.
  }

  /* -------------------------------------------- */

  /** @inheritDoc */
  async _preUpdate(changed, options, user) {
    if ((await super._preUpdate(changed, options, user)) === false) return false;
    // A Miko's tradition abilities must be removed before changing tradition.
    const tradition = changed.system?.tradition;
    if (this.type === 'character' && tradition !== undefined) {
      const error = validateTraditionChange(this, tradition);
      if (error) {
        ui.notifications.warn(error);
        return false;
      }
    }
  }

  /** @inheritDoc */
  _onUpdate(changed, options, userId) {
    super._onUpdate(changed, options, userId);
    if (userId === game.user.id) this.syncClassEffects();
  }

  /**
   * Create, update, or remove the system-managed Active Effects for class features (ninja
   * exhaustion, Gates and Jinchuriki flaws; Samurai Oni's Might). Calls are queued so
   * overlapping updates can't duplicate effects.
   * @returns {Promise<void>}
   */
  syncClassEffects() {
    if (this.type !== 'character') return Promise.resolve();
    this._classEffectSync = (this._classEffectSync ?? Promise.resolve())
      .then(() => syncClassEffects(this))
      .catch((err) => console.error('casus-belli | Failed to sync class effects', err));
    return this._classEffectSync;
  }

  /**
   * @override
   * Augment the actor source data with additional dynamic data that isn't 
   * handled by the actor's DataModel. Data calculated in this step should be
   * available both inside and outside of character sheets (such as if an actor
   * is queried and has a roll executed directly from it).
   */
  prepareDerivedData() {
    const actorData = this;
    const flags = actorData.flags['casus-belli'] || {};

    if (actorData.type === 'character' && actorData.system?.pain) {
      let woundPain = 0;
      for (const item of this.items) {
        if (item.type === 'wound') {
          woundPain += Number(item.system.pain) || 0;
        }
      }
      // painModifier is driven by Active Effects (e.g. the Wracked by Pain flaw).
      actorData.system.pain.value = Math.max(0, woundPain + (Number(actorData.system.painModifier) || 0));
    }

    if (actorData.type === 'character' && actorData.system?.carryingCapacity) {
      let totalWeight = 0;
      for (const item of this.items) {
        if (item.type === 'item') {
          const isEquipped = Boolean(item.system?.equipped);
          if (!isEquipped) continue;
          const itemWeight = Number(item.system?.weight ?? 0);
          const itemQuantity = Number(item.system?.quantity ?? 1);
          if (!Number.isNaN(itemWeight) && !Number.isNaN(itemQuantity)) {
            totalWeight += itemWeight * itemQuantity;
          }
        } else if (item.type === 'armor') {
          const armorWeight = Number(item.system?.weight ?? 0);
          if (!Number.isNaN(armorWeight)) {
            totalWeight += armorWeight;
          }
        } else if (item.type === 'gadget') {
          const gadgetWeight = Number(item.system?.weight ?? 0);
          const isEquipped = Boolean(item.system?.equipped);
          if (isEquipped && !Number.isNaN(gadgetWeight)) {
            totalWeight += gadgetWeight;
          }
        }
      }
      actorData.system.carryingCapacity.value = totalWeight;
    }
  }

  /**
   * 
   * @override
   * Augment the actor's default getRollData() method by appending the data object
   * generated by the its DataModel's getRollData(), or null. This polymorphic 
   * approach is useful when you have actors & items that share a parent Document, 
   * but have slightly different data preparation needs.
   */
  getRollData() {
    return { ...super.getRollData(), ...this.system.getRollData?.() ?? null };
  }

  /**
   * Convert the actor document to a plain object.
   * 
   * The built in `toObject()` method will ignore derived data when using Data Models.
   * This additional method will instead use the spread operator to return a simplified
   * version of the data.
   * 
   * @returns {object} Plain object either via deepClone or the spread operator.
   */
  toPlainObject() {
    const result = {...this};

    // Simplify system data.
    result.system = this.system.toPlainObject();

    // Add items.
    result.items = this.items?.size > 0 ? this.items.contents : [];

    // Add effects.
    result.effects = this.effects?.size > 0 ? this.effects.contents : [];

    return result;
  }

}
